const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const storage=new Map();
const controls={difficulty:{value:'3'},register:{value:'60'},timbre:{value:'soft'}};
const sandbox={localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)},console};
vm.createContext(sandbox);
vm.runInContext(readFileSync('dist/records.js','utf8'),sandbox);
sandbox.$=id=>controls[id];
vm.runInContext("let mode='match',target=[60],selection=[62]; function renderRecords(){}",sandbox);
const run=code=>vm.runInContext(code,sandbox);
run('recordAttempt(false,false,[60])');
assert.equal(run('records.topics[topicKey(topicContext())].wrong'),1);
assert.equal(run('records.mistakes.length'),1);
run('recordAttempt(true,false,[60])');
assert.equal(run('records.mistakes.length'),1,'same question merges');
assert.equal(run('records.mistakes[0].occurrences'),2);
assert.equal(run('records.topics[topicKey(topicContext())].revealed'),1);
controls.difficulty.value='fga';
run('target=[65]; selection=[67]; recordAttempt(false,false,[65])');
assert.equal(run('Object.keys(records.topics).length'),2,'ranges remain separate');
controls.difficulty.value='3';
run('currentReview=records.mistakes[0].id; target=[60]; selection=[60]; recordAttempt(false,true,[60])');
assert.equal(run('records.mistakes[0].resolved'),true);
assert.equal(run('records.topics[topicKey(topicContext())].total'),2,'review does not inflate first attempts');
assert.equal(run('records.topics[topicKey(topicContext())].reviewCorrect'),1);
run('selection=[62]; recordAttempt(false,false,[60])');
assert.equal(run('records.mistakes[0].resolved'),false,'wrong retry remains pending');
run('selection=[]; recordAttempt(true,false,[60])');
assert.equal(run('records.mistakes[0].resolved'),false,'reveal never resolves');
for(const [m,t,a,s] of [['direction',[60,64],[2],[0]],['bass',[60,62,64],[60,62,64],[60,64,62]],['chord',[60,1],[1],[0]]]){
  sandbox.testMode=m;sandbox.testTarget=t;sandbox.testAnswer=a;sandbox.testSelection=s;
  run('currentReview=null;mode=testMode;target=testTarget;selection=testSelection;recordAttempt(false,false,testAnswer)');
}
assert.equal(run('records.mistakes.length'),5,'all four modes record exact targets');
assert.deepEqual(Array.from(run("records.mistakes.find(m=>m.context.mode==='chord').target")),[60,1]);
const restored={localStorage:sandbox.localStorage};vm.createContext(restored);vm.runInContext(readFileSync('dist/records.js','utf8'),restored);
assert.equal(vm.runInContext('records.mistakes.length',restored),5,'records survive reload');
console.log('PASS: topic separation, deduplication, reveal, retry scoring, exact targets, persistence');
